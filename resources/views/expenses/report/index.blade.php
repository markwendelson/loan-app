@push('js')
    <script src="{{ url('assets/js/datepicker/date-picker/datepicker.js') }}"></script>

    <script>
        $(document).ready(function() {
            //handle all checkbox behaviour
            $(".mainAll").on("change", function() {
                if ($(this).is(":checked")) {
                    $(".chckAll").prop("checked", true);
                } else {
                    $(".chckAll").prop("checked", false);
                }
            });

            //handle categories checkbox behaviour
            $(".chckAll").on("change", function() {
                let total = $(".chckAll").length;
                let checked = $(".chckAll:checked").length;

                if (checked === total) {
                    $(".mainAll").prop("checked", true);
                } else {
                    $(".mainAll").prop("checked", false);
                }
            });

            $('.expenseDate').daterangepicker({
                opens: 'right',
                autoUpdateInput: false,
                locale: {
                    cancelLabel: 'Cancel',
                    format: 'MM/DD/YYYY'
                },
                singleDatePicker: false,
            });

            // Event triggered when "Apply" is clicked
            $('.expenseDate').on('apply.daterangepicker', function(ev, picker) {
                let start = picker.startDate.format('MM/DD/YYYY');
                let end = picker.endDate.format('MM/DD/YYYY');

                $(this).val(`${start} - ${end}`);

                console.log('Selected range:', start, 'to', end);
            });
        });

        $(".btnGenerateReport").click(function(e) {
            e.preventDefault();

            $("#modalExpensesReport").modal("show");
        })

        //handle modal cancel button
        $("#modalExpensesReport .btnCancel").click(function(e) {
            e.preventDefault();

            $("#modalExpensesReport").modal("hide");
        })

        $("#modalExpensesReport .btnSubmit").click(function(e) {
            let formData = $("#modalExpensesReport form").serializeArray();

            $(".loader-wrapper").fadeIn("slow");

            $.ajax({
                type: "POST",
                url: "{{ route('expense.create-report') }}",
                data: formData,
                dataType: "json",
                headers: {
                    'X-CSRF-TOKEN': $('meta[name="csrf-token"]').attr('content')
                },
                success: function (response) {
                    //hide loading form
                    $(".loader-wrapper").fadeOut("slow", function () {
                        $(this).hide();
                    });

                    if( response.status !== 'undefined' && response.status =='success') {
                        swal({
                            title: 'Success!',
                            text: response.message,
                            icon: 'success',
                            buttons: {
                                confirm: {
                                    text: "OK",
                                    value: true,
                                    visible: true,
                                    className: "btn btn-primary",
                                    closeModal: true
                                }
                            },
                        }).then((willClose) => {
                            if (willClose) {
                                location.reload();
                            }
                        });
                    }else{
                        swal({
                            title: 'Error!',
                            text: response.message,
                            icon: 'error',
                            buttons: {
                                confirm: {
                                    text: "OK",
                                    value: true,
                                    visible: true,
                                    className: "btn btn-primary",
                                    closeModal: true
                                }
                            },
                        });
                    }
                }
            });

            return console.log(formData);
        })
    </script>
@endpush